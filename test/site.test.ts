import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, readdir, rm, writeFile, cp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { buildSite } from '../src/build-site.js';
import { libraryCard, buildDiscovery } from '../src/site-content.js';
import { registrySchema } from '../src/types.js';

test('buildSite bundles shared Geist, preserves registry bytes and links to IDE', async (t) => {
  const root = await mkdtemp(join(tmpdir(), 'scad-registry-pages-'));
  t.after(async () => rm(root, { recursive: true, force: true }));
  await cp(join(process.cwd(),'web'),join(root,'web'),{recursive:true});
  await mkdir(join(root,'dist'));
  const date='2026-11-26T00:00:00Z';
  const sample=registrySchema.parse({schemaVersion:1,generatedAt:date,libraries:[{id:'example',name:'Example & <Library>',description:'A test with </script> and & characters.',repositoryUrl:'https://github.com/example/library',documentationUrl:'https://github.com/example/library/wiki',license:'MIT',defaultBranch:null,archived:null,versions:[],latestVersion:null,sync:{status:'error',attemptedAt:date,lastSuccessAt:null,error:'fixture'}}]});
  const registry=JSON.stringify(sample);
  await writeFile(join(root,'dist','registry.json'),registry);
  const fonts=join(root,'.cache','pages-fonts','node_modules','geist');
  for(const [folder,name] of [['geist-sans','Geist-Variable.woff2'],['geist-mono','GeistMono-Variable.woff2']] as const){
    await mkdir(join(fonts,'dist','fonts',folder),{recursive:true});
    await writeFile(join(fonts,'dist','fonts',folder,name),'wOF2fixture');
  }
  await writeFile(join(fonts,'LICENSE.TXT'),'fixture license');
  await buildSite(root);
  const output=await readdir(join(root,'dist'));
  assert.equal(await readFile(join(root,'dist','registry.json'),'utf8'),registry);
  const html=await readFile(join(root,'dist','index.html'),'utf8');
  assert.match(html,/<html lang="en" data-theme="light">/);
  assert.equal((html.match(/rel="stylesheet"/g)||[]).length,1);
  assert.ok((html.match(/href="https:\/\/peterisdev42\.github\.io\/scad-ai-ide\//g)||[]).length>=3);
  assert.match(html,/data-theme-toggle/);
  assert.match(html,/id="library-search"/);
  assert.match(html,/id="library-grid"/);
  assert.doesNotMatch(html,/id="updated"|catalog-meta/);
  const app=output.find(name=>/^app\.[a-f0-9]{16}\.js$/.test(name));
  assert.ok(app);
  assert.ok(html.includes('src="./'+app+'"'));
  const script=await readFile(join(root,'dist',app),'utf8');
  assert.doesNotMatch(script,/fetch\(|cardFor\(|replaceChildren|details-panel|card-icon/);
  assert.match(script,/card\.hidden = !visible/);
  assert.match(html,/id="library-example"/);
  assert.match(html,/Example &amp; &lt;Library&gt;/);
  assert.match(html,/A test with &lt;\/script&gt; and &amp; characters\./);
  assert.doesNotMatch(html,/<div class="library-grid" id="library-grid"><\/div>/);
  assert.equal((html.match(/class="library-card"/g)||[]).length,sample.libraries.length);
  const graph=JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)![1]!);
  assert.equal(graph['@graph'].find((n:{'@type':string})=>n['@type']==='Dataset').distribution.contentUrl,'https://peterisdev42.github.io/scad-registry/registry.json');
  const items=graph['@graph'].find((n:{'@type':string})=>n['@type']==='ItemList');
  assert.equal(items.numberOfItems,sample.libraries.length);
  assert.equal(items.itemListElement[0].item.name,sample.libraries[0]!.name);
  assert.equal(items.itemListElement[0].item.url,'https://peterisdev42.github.io/scad-registry/#library-example');
  const llms=await readFile(join(root,'dist','llms.txt'),'utf8');
  assert.ok(llms.startsWith('# SCAD Registry — part of the SCAD AI IDE ecosystem\n'));
  assert.ok(llms.indexOf('## Main product: SCAD AI IDE')<llms.indexOf('## Registry resources'));
  for(const suffix of ['product.json','llms.txt','#library-management','#getting-started','#status'])assert.ok(llms.includes('https://peterisdev42.github.io/scad-ai-ide/'+suffix));
  const ideId='https://peterisdev42.github.io/scad-ai-ide/#application';
  const ide=graph['@graph'].find((n:{'@type':string})=>n['@type']==='SoftwareApplication');
  assert.equal(ide['@id'],ideId);
  assert.equal(ide.name,'SCAD AI IDE');
  assert.equal(graph['@graph'].find((n:{'@type':string})=>n['@type']==='CollectionPage').about['@id'],ideId);
  assert.equal(graph['@graph'].find((n:{'@type':string})=>n['@type']==='Dataset').about['@id'],ideId);
  assert.match(html,/<title>SCAD Registry — OpenSCAD Libraries for SCAD AI IDE<\/title>/);
  assert.match(html,/<link rel="canonical" href="https:\/\/peterisdev42\.github\.io\/scad-registry\/">/);
  assert.match(html,/id="scad-ai-ide"/);
  const full=await readFile(join(root,'dist','llms-full.txt'),'utf8');
  assert.ok(full.includes('Registry ID: example'));
  assert.ok(full.indexOf('## Main product: SCAD AI IDE')<full.indexOf('## Libraries'));
  assert.ok(full.includes('https://peterisdev42.github.io/scad-ai-ide/product.json'));
  assert.ok(full.includes('https://github.com/example/library/wiki'));
  assert.match(await readFile(join(root,'dist','sitemap.xml'),'utf8'),/<loc>https:\/\/peterisdev42\.github\.io\/scad-registry\/<\/loc>/);
  assert.match(html,/id="faq"/);
  assert.match(html,/id="registry-api"/);
  assert.match(html,/<meta property="og:image" content="https:\/\/peterisdev42\.github\.io\/scad-registry\/assets\/og-card\.png">/);
  const png=await readFile(join(root,'dist','assets','og-card.png'));
  assert.equal(png.subarray(0,8).toString('hex'),'89504e470d0a1a0a');
  assert.equal(png.readUInt32BE(16),1200);
  assert.equal(png.readUInt32BE(20),630);
  for(const [,href] of html.matchAll(/href="(#[^"]+)"/g))assert.ok(html.includes('id="'+href!.slice(1)+'"'),href);
  const noDocs=libraryCard({...sample.libraries[0]!,documentationUrl:null});
  assert.doesNotMatch(noDocs,/card-documentation/);
  assert.match(noDocs,/card-repository/);
  assert.doesNotMatch(libraryCard({...sample.libraries[0]!,documentationUrl:'javascript:alert(1)'}),/card-documentation|javascript:/);
  assert.doesNotMatch(libraryCard({...sample.libraries[0]!,documentationUrl:'https://user:pass@example.com/'}),/card-documentation|user:pass/);
  assert.doesNotMatch(noDocs,/Default branch|Available versions|Show details|card-icon/);
  assert.ok(buildDiscovery(sample).jsonLd.includes('\\u003c'));
  const css=output.find(name=>/^site\.[a-f0-9]{16}\.css$/.test(name));
  assert.ok(css);
  const contents=await readFile(join(root,'dist',css),'utf8');
  assert.match(contents,/\.\/assets\/fonts\/Geist-Variable\.woff2/);
  assert.doesNotMatch(contents,/@import|\.card-icon\s*\{/);
  assert.match(contents,/\.card-footer\s*\{[^}]*justify-content: space-between/);
  assert.match(contents,/\.card-actions \.geist-button\s*\{[^}]*align-items: center; justify-content: center/);
  assert.match(contents,/scroll-padding-top: var\(--header-height\)/);
  for(const name of ['.nojekyll','favicon.svg','index.html','assets','geist','llms.txt','llms-full.txt','sitemap.xml']) assert.ok(output.includes(name));
  assert.equal(await readFile(join(root,'dist','assets','fonts','LICENSE.txt'),'utf8'),'fixture license');
});
test('buildSite refuses to publish without a generated registry', async (t) => {
  const root = await mkdtemp(join(tmpdir(), 'scad-registry-pages-'));
  t.after(async () => rm(root, { recursive: true, force: true }));
  await assert.rejects(buildSite(root), /Missing dist\/registry.json/);
});
